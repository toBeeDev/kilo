/** 영문 종목명 → 대략의 한글. 번역 못 한 단어는 영문 그대로 남는다. */
export function autoKo(en: string): string {
  let s = en.replace(/_/g, " ").replace(/\s+-\s+/g, " · "); // "A - B" 는 구분점, "Anti-Gravity" 는 한 단어
  for (const [re, ko] of EN_KO) s = s.replace(re, ko);
  return s
    .replace(/\(\s*\)/g, "")
    .replace(/\s{2,}/g, " ")
    .replace(/\s+\)/g, ")")
    .replace(/\s*·\s*/g, " · ")
    .replace(/(·\s*){2,}/g, "· ")
    .replace(/^[\s·&]+|[\s·&]+$/g, "")
    .trim();
}
